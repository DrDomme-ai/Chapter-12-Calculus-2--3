const note = (type, title, value) => {
  const block = typeof value === 'string' ? { content: value } : value
  return {
    type,
    title,
    content: block?.content || '',
    ...(block?.math ? { math: block.math } : {}),
  }
}

const presenterNotes = ({
  topic = 'the geometric idea',
  goal = `Make ${topic} visible before attaching formal language to it.`,
  say = 'Describe what you notice before we name the rule.',
  ask = 'What changes, and what remains fixed?',
  expected = 'Students should describe a visible invariant in their own words.',
  unsure = 'Point to one feature at a time and ask students to compare two concrete cases.',
  draw = 'Use the displayed construction and add only the labels needed for the current idea.',
  reveal = 'Reveal one mathematical layer at a time after students make a prediction.',
  definition = `State the definition of ${topic} only after the visual meaning is clear.`,
  proof = 'No formal proof is required here; use the construction as the immediate justification.',
  solution = 'No separate computation is needed on this slide.',
  mistakes = 'Do not let a conclusion rest only on how the picture happens to look.',
  connection = 'Coordinate descriptions of geometry become equations, graphs, vectors, and rates of change in calculus.',
  transition = 'Use the final observation to motivate the next geometric question.',
} = {}) => [
  note('teaching', 'TEACHING GOAL', goal),
  note('script', 'WHAT TO SAY', say),
  note('ask', 'ASK STUDENTS', ask),
  note('response', 'EXPECTED RESPONSE', expected),
  note('support', 'IF STUDENTS ARE UNSURE', unsure),
  note('write', 'WHAT TO DRAW', draw),
  note('reveal', 'WHAT TO REVEAL', reveal),
  note('definition', 'DEFINITION EXPLANATION', definition),
  note('derivation', 'PROOF / DERIVATION', proof),
  note('solution', 'COMPLETE EXAMPLE SOLUTION', solution),
  note('common-mistake', 'COMMON MISTAKES', mistakes),
  note('connection', 'CONNECTION TO CALCULUS', connection),
  note('transition', 'TRANSITION', transition),
]

const content = (kind, value) => ({ kind, value })
const eyebrow = (value) => content('eyebrow', value)
const text = (value) => content('text', value)
const math = (value) => content('math', value)
const list = (value) => content('list', value)
const callout = (value) => content('callout', value)

const slide = (id, title, type, items = [], options = {}) => ({
  id,
  title,
  type,
  presentationContent: items,
  presenterNotes: presenterNotes({ topic: title, ...options.notes }),
  studentNotes: options.studentNotes || [],
  revealSteps: options.revealSteps || [],
  courses: options.courses || ['calc2', 'calc3'],
  recommendedFor: options.recommendedFor || ['calc2', 'calc3'],
  level: options.level || 'essential',
  visualization: options.visualization,
  question: options.question,
  theme: 'classic-math',
  layoutMode: 'slide',
})

